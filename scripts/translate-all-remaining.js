// Process all keys in rw.ts
let translatedCount = 0;
for (const [key, val] of Object.entries(rw)) {
  const enVal = en[key] || "";
  
  if (rwDetailedMap[key]) {
    rw[key] = rwDetailedMap[key];
    translatedCount++;
  } else if (val === enVal && enVal.trim().length > 3) {
    let replaced = false;
    for (const [pattern, replacement] of translationRules) {
      if (pattern.test(enVal)) {
        rw[key] = enVal.replace(pattern, replacement);
        replaced = true;
        translatedCount++;
        break;
      }
    }
  }
}

console.log("Updated Kinyarwanda translations count:", translatedCount);

function serializeDict(dict, name) {
  const sortedKeys = Object.keys(dict).sort();
  let code = `const ${name}: Record<string, string> = {\n`;
  for (const k of sortedKeys) {
    const v = dict[k] || "";
    const escapedVal = v.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n");
    code += `  "${k}": "${escapedVal}",\n`;
  }
  code += `};\n\nexport default ${name};\n`;
  return code;
}

