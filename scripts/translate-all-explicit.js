for (const [k, v] of Object.entries(rw)) {
  const enVal = en[k] || "";
  
  if (explicitMap[k]) {
    rw[k] = explicitMap[k];
    applied++;
  } else if (v === enVal && enVal.trim().length > 3) {
    // Check if key ends with something in explicitMap
    const parts = k.split(".");
    const lastPart = parts[parts.length - 1];
    if (explicitMap[lastPart]) {
      rw[k] = explicitMap[lastPart];
      applied++;
    }
  }
}

